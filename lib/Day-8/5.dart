//* Q5: Eligibility Checker:
//* marks = 75, attendance = 80
//* Check: marks >= 60 && attendance >= 75
//* Print whether student is eligible (true/false)

void main() {
  int marks = 75;
  int attendance = 80;
  if (marks >= 60 && attendance >= 75) {
    print("Student is Eligible");
  } else {
    print("Student is not Eligible");
  }
}
