//* Question 4: Arithmetic Practice
//* Take two numbers 45 and 8. Perform all arithmetic operations (+, -, *, /, %, ~/). Print each result with proper labels.

void main() {
  int a = 45;
  int b = 8;
  print("Addition: ${a + b}");
  print("Subtraction: ${a - b}");
  print("Multiplication: ${a * b}");
  print("Division: ${a / b}");
  print("Modulus: ${a % b}");
  print("Division: ${a ~/ b}");
}
