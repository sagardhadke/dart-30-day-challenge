//* Question 5: Comparison Basics
//* Create two variables: yourAge = 22, friendAge = 25. Compare them using all comparison operators (==, !=, >, <, >=, <=) and print results.

void main() {
  int yourAge = 22;
  int friendAge = 25;

  print(yourAge == friendAge);
  print(yourAge != friendAge);
  print(yourAge > friendAge);
  print(yourAge < friendAge);
  print(yourAge >= friendAge);
  print(yourAge <= friendAge);
}
