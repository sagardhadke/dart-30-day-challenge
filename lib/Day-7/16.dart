//* Q16. Counter Operations: Create counter = 100:
//* Use counter += 50 (add 50)
//* Use counter -= 30 (subtract 30)
//* Use counter *= 2 (double it)
//* Use counter ~/= 5 (divide by 5 using integer division)
//* Print after each operation

void main() {
  int counter = 100;
  print(counter += 50);
  print(counter -= 30);
  print(counter *= 2);
  print(counter ~/= 5);
}
