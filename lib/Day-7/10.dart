//* Q10. Expression Evaluation: Calculate and print: (5 + 3) * 2 - 10 / 2. Understand operator precedence (BODMAS).

void main() {
  print((5 + 3) * 2 - 10 / 2);

  print("B: ${(5 + 3)}");
  print("O: ${2 * 2}");
  print("D: ${10 / 2}");
  print("M: ${3 * 2}");
  print("A: ${5 + 3}");
  print("S: ${5 - 3}");
}
