//* Q11. Comparison Operators Practice: Create two variables x = 15 and y = 20. Print results of:
//* x == y (equal to)
//* x != y (not equal to)
//* x > y (greater than)
//* x < y (less than)
//* x >= y (greater than or equal to)
//* x <= y (less than or equal to)

void main() {
  int x = 15;
  int y = 20;

  print(x == y);
  print(x != y);
  print(x > y);
  print(x < y);
  print(x >= y);
  print(x <= y);
}
