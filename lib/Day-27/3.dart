//* Question 3: Addition Function
//* Create a function named add() that takes two numbers as positional parameters and returns their sum. Call it with different numbers and print results.

num add(num a, num b) {
  return a + b;
}

void main() {
  print(add(5, 3));
  print(add(10, 20));
  print(add(2.5, 7.5));
}
